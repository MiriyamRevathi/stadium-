/**
 * Creates SVG arc path string for an annular sector
 */
export function describeArcSector(
  cx: number,
  cy: number,
  rInner: number,
  rOuter: number,
  startAngleDeg: number,
  endAngleDeg: number
): string {
  const toRad = (deg: number) => ((deg - 90) * Math.PI) / 180;
  const startRad = toRad(startAngleDeg);
  const endRad = toRad(endAngleDeg);

  const largeArcFlag = endAngleDeg - startAngleDeg <= 180 ? 0 : 1;

  // Outer arc points
  const x1 = cx + rOuter * Math.cos(startRad);
  const y1 = cy + rOuter * Math.sin(startRad);
  const x2 = cx + rOuter * Math.cos(endRad);
  const y2 = cy + rOuter * Math.sin(endRad);

  // Inner arc points
  const x3 = cx + rInner * Math.cos(endRad);
  const y3 = cy + rInner * Math.sin(endRad);
  const x4 = cx + rInner * Math.cos(startRad);
  const y4 = cy + rInner * Math.sin(startRad);

  return [
    `M ${x1.toFixed(1)} ${y1.toFixed(1)}`,
    `A ${rOuter} ${rOuter} 0 ${largeArcFlag} 1 ${x2.toFixed(1)} ${y2.toFixed(1)}`,
    `L ${x3.toFixed(1)} ${y3.toFixed(1)}`,
    `A ${rInner} ${rInner} 0 ${largeArcFlag} 0 ${x4.toFixed(1)} ${y4.toFixed(1)}`,
    'Z'
  ].join(' ');
}

export function getSectorCenter(
  cx: number,
  cy: number,
  rInner: number,
  rOuter: number,
  startAngleDeg: number,
  endAngleDeg: number
): { x: number; y: number } {
  const midAngle = (startAngleDeg + endAngleDeg) / 2;
  const midRadius = (rInner + rOuter) / 2;
  const rad = ((midAngle - 90) * Math.PI) / 180;
  return {
    x: Math.round(cx + midRadius * Math.cos(rad)),
    y: Math.round(cy + midRadius * Math.sin(rad))
  };
}

